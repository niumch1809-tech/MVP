const DEFAULT_ADVICE: MaterialNegotiationAdvice = {
  factors: "规格、数量、单位、品牌、工艺、起订量、损耗和是否包含附加费用",
  verify: "核对规格、单位、每套用量、品牌档位、工艺要求和报价包含范围",
  direction: "要求供应商拆分主要成本构成，并在同一规格、用量和费用边界下重新报价",
  watchFor: "名称相近但规格不同、单位换算错误、合并计价重复累计，或一次性费用混入单价",
  singleAction: "先补齐规格、单位和用量，再要求拆分材料、加工、损耗与附加费用"
};

function rule(
  pattern: RegExp,
  factors: string,
  verify: string,
  direction: string,
  watchFor: string,
  singleAction: string
): AdviceRule {
  return { pattern, advice: { factors, verify, direction, watchFor, singleAction } };
}

export function getMaterialNegotiationAdvice(materialName: string, category = ""): MaterialNegotiationAdvice {
  const value = `${category} ${materialName}`;
  return RULES.find((item) => item.pattern.test(value))?.advice ?? DEFAULT_ADVICE;
}
